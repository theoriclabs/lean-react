// One LeanReact release per Lean minor version: the README's version table lists this
// checkout's Lean version with the LeanReact version in lakefile.toml, and LeanJS stamps
// the same Lean version into generated modules. `--tag vX.Y.Z` also checks a release tag.
import { readFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const read = file => readFile(new URL(file, `file://${root}`), 'utf8');
const toolchain = (await read('lean-toolchain')).trim();
const lean = toolchain.match(/^leanprover\/lean4:v(\d+)\.(\d+)\.(\d+)$/);
if (!lean) throw new Error(`lean-toolchain is not a Lean release: ${toolchain}`);
const [, major, minor, patch] = lean;
const version = (await read('lakefile.toml')).match(/^version\s*=\s*"([^"]+)"/m)?.[1];
if (!version) throw new Error('lakefile.toml has no version');
const problems = [];
const readme = await read('README.md');
const row = readme.split('\n').find(line => line.startsWith(`| ${major}.${minor} |`));
if (!row) problems.push(`README.md: the Lean versions table has no row for Lean ${major}.${minor}`);
else if (!row.includes(`v${version}`)) problems.push(`README.md: the Lean ${major}.${minor} row does not name v${version}: ${row}`);
const compiler = await read('engine/LeanJS/Compiler.lean');
const stamped = `${major}.${minor}.${patch}`;
for (const needle of [`Generated by LeanJS for Lean ${stamped}`, `interface.lean == "${stamped}"`, `("lean", toJson "${stamped}")`])
  if (!compiler.includes(needle)) problems.push(`engine/LeanJS/Compiler.lean does not stamp Lean ${stamped}: missing ${needle}`);
const tagIndex = process.argv.indexOf('--tag');
if (tagIndex >= 0 && process.argv[tagIndex + 1] !== `v${version}`)
  problems.push(`tag ${process.argv[tagIndex + 1]} does not match lakefile.toml version v${version}`);
if (problems.length) { for (const problem of problems) console.error(problem); process.exit(1); }
console.log(`LeanReact v${version} supports Lean ${stamped}; README.md and LeanJS agree.`);
