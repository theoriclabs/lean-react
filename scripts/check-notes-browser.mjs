// Fresh automated browser contexts only. Opt-in mutations for public deployments.
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { mkdir } from 'node:fs/promises';
import { chromium, expect } from '@playwright/test';
const origin = new URL(process.argv[2] ?? 'http://127.0.0.1:4190').origin;
if (!['localhost', '127.0.0.1'].includes(new URL(origin).hostname) && !process.argv.includes('--allow-mutations'))
  throw new Error('Hosted checks create disposable synthetic test accounts: pass --allow-mutations');
const browser = await chromium.launch({ executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH });
const context = await browser.newContext({ viewport: { width: 1440, height: 1100 }, reducedMotion: 'reduce' });
const page = await context.newPage();
const problems = []; page.on('pageerror', e => problems.push(e.message));
const name = `notes_${randomUUID().slice(0, 12)}`, password = randomUUID() + randomUUID();
try {
  await page.goto(origin);
  await expect(page.getByRole('heading', { name: 'Private by proof.' })).toBeVisible();
  await expect(page.getByText('9', { exact: true })).toBeVisible();
  await page.getByLabel('Username', { exact: true }).fill(name);
  await page.getByLabel('Disposable password').fill(password);
  await page.getByRole('button', { name: 'Create my test workspace' }).click();
  await expect(page.getByRole('heading', { name: `${name}’s notes` })).toBeVisible();
  await expect(page.locator('.note')).toHaveCount(2);
  await expect(page.getByRole('heading', { name: 'Garden notes', exact: true })).toBeVisible();
  await page.getByLabel('Search your notes').fill('budget');
  await page.getByRole('button', { name: 'Search', exact: true }).click();
  await expect(page.locator('.note')).toHaveCount(1);
  await expect(page.getByText('1 authorized match.', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Read another owner’s note' }).click();
  await expect(page.locator('.probe-result')).toContainText('404 · notes.not_found');
  await page.getByRole('button', { name: 'Read your archived-tenant note' }).click();
  await expect(page.locator('.probe-result')).toContainText('Same owner, other tenant → 404');
  await page.getByRole('button', { name: 'Read a nonexistent note' }).click();
  await expect(page.locator('.probe-result')).toContainText('Missing note → 404');
  const downloading = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export JSON' }).click();
  const download = await downloading, stream = await download.createReadStream();
  let text = ''; for await (const chunk of stream) text += chunk;
  const exported = JSON.parse(text);
  assert.equal(exported.length, 1); assert.equal(exported[0].title, 'Launch budget');
  assert.ok(!text.includes('CANARY'));
  await page.reload(); await expect(page.locator('.note')).toHaveCount(2);
  const cookies = await context.cookies(origin);
  const cookie = cookies.find(c => c.name === (origin.startsWith('https:') ? '__Host-leanapp_session' : 'leanapp_session'));
  assert.ok(cookie?.httpOnly); assert.equal(cookie.sameSite, 'Strict');
  if (origin.startsWith('https:')) assert.equal(cookie.secure, true);
  assert.deepEqual(await page.evaluate(() => [document.cookie, localStorage.length, sessionStorage.length]), ['', 0, 0]);
  await mkdir(new URL('../.lake/security/', import.meta.url), { recursive: true });
  await page.screenshot({ path: new URL('../.lake/security/notes-workspace.png', import.meta.url).pathname, fullPage: true });
  await page.getByRole('button', { name: /Inspect agent changes/ }).click();
  await expect(page.getByRole('heading', { name: /Add export/ })).toBeVisible();
  await expect(page.locator('.diagnostic')).toContainText('error:');
  await page.getByRole('button', { name: 'An agent replaces the proof with sorry' }).click();
  await expect(page.locator('.diagnostic')).toContainText('sorryAx');
  await page.getByRole('button', { name: 'An agent changes the policy itself' }).click();
  await expect(page.locator('.diagnostic')).toContainText('candidate policy differs');
  await page.getByRole('button', { name: 'Keep the ownership contract' }).click();
  await expect(page.locator('.success-text')).toHaveText('✓ Accepted');
  await page.screenshot({ path: new URL('../.lake/security/notes-agent.png', import.meta.url).pathname, fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.getByRole('button', { name: /Try private notes/ }).click();
  await expect(page.locator('.note')).toHaveCount(2);
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.getByRole('button', { name: 'Log out', exact: true }).click();
  await expect(page.locator('.note')).toHaveCount(0);
  await expect(page.getByLabel('Disposable password')).toHaveValue('');
  await page.getByRole('button', { name: 'Already have an account? Log in' }).click();
  await page.getByLabel('Username', { exact: true }).fill(name);
  await page.getByLabel('Disposable password').fill(password);
  await page.getByRole('button', { name: 'Log in →', exact: true }).click();
  await expect(page.locator('.note')).toHaveCount(2);
  assert.deepEqual(problems, []);
  console.log('PASS: browser signup, private notes, search, direct probes, JSON export, restore, logout/login, agent evidence, mobile layout and cookie boundary. One disposable synthetic account remains; no credentials recorded.');
} finally { await browser.close(); }
